<#
.SYNOPSIS
    Writes THIRD-PARTY-NOTICES.txt from the packages this build actually ships.

.DESCRIPTION
    Reads the restored package graph (project.assets.json) for the win-x64 target and keeps the packages that put
    files in the app (runtime or native assets). For each it takes the licence and copyright from the package's
    .nuspec, and appends every licence/notice file the package carries (duplicates removed). Components that do not
    come from a NuGet package's metadata (the .NET runtime, PDFium's bundled libraries, Leptonica, the PaddleOCR
    models) are described below by hand. Run by build.ps1; can be run on its own after a restore.
#>
param([string]$Out = (Join-Path (Split-Path $PSScriptRoot -Parent) 'THIRD-PARTY-NOTICES.txt'))
$ErrorActionPreference = 'Stop'

$root = Split-Path $PSScriptRoot -Parent
$packages = Join-Path $env:USERPROFILE '.nuget\packages'
$dotnetRoot = Join-Path $env:USERPROFILE 'source\tools\dotnet8'
$assetsFile = Join-Path $env:USERPROFILE 'source\build\PdfTranslator\obj\project.assets.json'
if (-not (Test-Path $assetsFile)) { throw "No restore output at $assetsFile - build first." }
$assets = Get-Content $assetsFile -Raw | ConvertFrom-Json

# Packages that ship files in the win-x64 app ("_._" placeholders ship nothing).
$target = $assets.targets.PSObject.Properties | Where-Object { $_.Name -like '*/win-x64' } | Select-Object -First 1
if (-not $target) { throw 'No win-x64 target in project.assets.json.' }
$shipped = foreach ($lib in $target.Value.PSObject.Properties) {
    if ($lib.Value.type -ne 'package') { continue }
    $files = @()
    foreach ($kind in 'runtime', 'native', 'runtimeTargets') {
        if ($lib.Value.$kind) { $files += $lib.Value.$kind.PSObject.Properties.Name | Where-Object { $_ -notlike '*/_._' } }
    }
    # runtimeTargets lists every OS; keep only those for Windows x64.
    $files = $files | Where-Object { $_ -notmatch '^runtimes/' -or $_ -match '^runtimes/win-x64/' }
    if ($files) { $lib.Name }
}

function Read-Nuspec([string]$name, [string]$version) {
    $dir = Join-Path $packages ("{0}\{1}" -f $name.ToLower(), $version)
    [xml]$x = Get-Content (Get-ChildItem $dir -Filter *.nuspec | Select-Object -First 1).FullName
    $m = $x.package.metadata
    $licence = if ($m.license) {
        if ($m.license.type -eq 'file') { "see " + $m.license.'#text' } else { $m.license.'#text' }
    } elseif ($m.licenseUrl) { $m.licenseUrl } else { 'see package' }
    [pscustomobject]@{
        Name = $m.id; Version = $m.version; Licence = $licence
        Copyright = if ($m.copyright) { $m.copyright } else { "Authors: $($m.authors)" }
        Url = if ($m.projectUrl) { $m.projectUrl } else { $m.repository.url }
        Dir = $dir
    }
}

