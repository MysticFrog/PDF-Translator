Rule '5. Licence and notice files supplied with the components'
$seen = @{}
$noticeFiles = @()
foreach ($i in $infos) {
    $noticeFiles += Get-ChildItem $i.Dir -File | Where-Object { $_.Name -match '^(licen[cs]e|notice|third[-_ ]?party|copying)' } |
        ForEach-Object { [pscustomobject]@{ Title = "$($i.Name) $($i.Version): $($_.Name)"; Path = $_.FullName } }
}
foreach ($f in 'LICENSE.txt', 'ThirdPartyNotices.txt') {
    $p = Join-Path $dotnetRoot $f
    if (Test-Path $p) { $noticeFiles += [pscustomobject]@{ Title = ".NET runtime: $f"; Path = $p } }
}
foreach ($n in $noticeFiles) {
    $text = (Get-Content $n.Path -Raw -Encoding UTF8).TrimEnd()
    $key = [BitConverter]::ToString([Security.Cryptography.SHA256]::Create().ComputeHash([Text.Encoding]::UTF8.GetBytes(($text -replace '\s+', ' '))))
    if ($seen.ContainsKey($key)) { Line "--- $($n.Title): same text as $($seen[$key]) ---"; Line; continue }
    $seen[$key] = $n.Title
    Line "--- $($n.Title) ---"
    Line
    Line $text
    Line
}

