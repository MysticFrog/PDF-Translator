<#
.SYNOPSIS
    Builds PDF Translator with the portable .NET 10 SDK, and optionally its installers.

.EXAMPLE
    .\build.ps1                 build (Release)
    .\build.ps1 -Run            build and start the app
    .\build.ps1 -Installer      also make both installers (see below)

.NOTES
    Deliverables go to dist\ in the project folder:
      PdfTranslatorSetup-<version>.exe          small: the app without .NET; setup gets the .NET Desktop Runtime
                                                when the PC doesn't have it (machine-wide for all users, else into
                                                the program's own "dotnet" folder, no administrator rights needed)
      PdfTranslatorSetup-<version>-offline.exe  everything inside (self-contained), for PCs without internet
      PdfTranslator\                            the self-contained app, as the offline installer carries it
    Compiler output and installer staging stay under %USERPROFILE%\source\build\PdfTranslator, off Google
    Drive (sync locks files mid-build). The installer is the BasicConnect-style single executable in
    tools\Setup: per-user by default, /allusers, /S, /D=, /nodesktop, /uninstall.
#>
param([string]$Configuration = "Release", [switch]$Run, [switch]$Installer)
$ErrorActionPreference = 'Stop'

$dotnet = Join-Path $env:USERPROFILE "source\tools\dotnet10\dotnet.exe"
if (-not (Test-Path $dotnet)) { throw "Portable SDK not found at $dotnet" }
$env:DOTNET_CLI_TELEMETRY_OPTOUT = "1"
$env:DOTNET_NOLOGO = "1"

$root = $PSScriptRoot
$buildDir = Join-Path $env:USERPROFILE "source\build\PdfTranslator"
$distDir = Join-Path $root "dist"
$project = Join-Path $root "PdfTranslator.csproj"

& $dotnet build $project -c $Configuration
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

$framework = ([xml](Get-Content $project)).Project.PropertyGroup.TargetFramework | Where-Object { $_ } | Select-Object -First 1
$exe = Join-Path $buildDir "bin\$Configuration\$framework\win-x64\PdfTranslator.exe"
Write-Host "Built: $exe"

if ($Installer) {
    # Third-party notices from the packages this build restored; published with the app.
    & (Join-Path $root 'tools\Notices.ps1')

    # Version: from the csproj, plus the commit count when the sources are in git.
    $version = ([xml](Get-Content $project)).Project.PropertyGroup.Version | Where-Object { $_ } | Select-Object -First 1
    # Same stamp as GitVersion.targets gives the application: version.commits+hash[.dirty].
    $commits = 0; $hash = 'local'
    try {
        $commits = [int](git -C $root rev-list --count HEAD 2>$null)
        $hash = (git -C $root rev-parse --short HEAD 2>$null)
        if (git -C $root status --porcelain --untracked-files=no 2>$null) { $hash += '.dirty' }
    } catch { }
    $fileVersion = "$version.$commits"

    # The installer's file version, generated (not tracked).
    $versionFile = Join-Path $root 'tools\Setup\Properties\BuildVersion.cs'
    @(
        '// GENERATED by build.ps1. Not tracked, not edited by hand.',
        "[assembly: System.Reflection.AssemblyFileVersion(`"$fileVersion`")]",
        "[assembly: System.Reflection.AssemblyInformationalVersion(`"$fileVersion+$hash`")]"
    ) | Set-Content -Path $versionFile -Encoding UTF8

    New-Item -ItemType Directory -Path $distDir -Force | Out-Null
    # An old installer that is open or still syncing (Google Drive) stays; it is not worth failing the build over.
    Get-ChildItem $distDir -Filter 'PdfTranslatorSetup-*.exe' -ErrorAction SilentlyContinue | Remove-Item -Force -ErrorAction SilentlyContinue
    Add-Type -AssemblyName System.IO.Compression.FileSystem

    # One installer: publish the app, pack it with the icon (and an EULA.txt when there is one), and build
    # tools\Setup around it. A framework-dependent payload also carries runtime.txt, the .NET channel setup
    # makes sure is on the PC ("10.0").
    function New-Installer([string]$config, [bool]$selfContained, [string]$publish, [string]$suffix) {
        if (Test-Path $publish) { Remove-Item $publish -Recurse -Force }
        & $dotnet publish $project -c $config -r win-x64 --self-contained $selfContained.ToString().ToLower() -o $publish
        if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

        $payload = Join-Path $buildDir "setup\payload-$config"
        if (Test-Path $payload) { Remove-Item $payload -Recurse -Force }
        New-Item -ItemType Directory -Path $payload -Force | Out-Null
        Write-Host "Payload : compressing ($config)..."
        [System.IO.Compression.ZipFile]::CreateFromDirectory($publish, (Join-Path $payload 'Payload.zip'),
            [System.IO.Compression.CompressionLevel]::Optimal, $false)
        Copy-Item (Join-Path $root 'Assets\PdfTranslator.ico') -Destination $payload -Force
        $eula = Join-Path $root 'EULA.txt'
        if (Test-Path $eula) { Copy-Item $eula -Destination $payload -Force; Write-Host 'Payload : EULA.txt included' }
        if (-not $selfContained) {
            ($framework -replace '^net(\d+\.\d+).*$', '$1') | Set-Content (Join-Path $payload 'runtime.txt') -NoNewline -Encoding ASCII
        }

        # --no-incremental: the two installers differ only in their embedded payload.
        & $dotnet build (Join-Path $root 'tools\Setup\Setup.csproj') -c Release --no-incremental "-p:PayloadDir=$payload\"
        if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }
        $final = Join-Path $distDir "PdfTranslatorSetup-$fileVersion$suffix.exe"
        Copy-Item (Join-Path $buildDir 'setup\bin\Release\net472\PdfTranslatorSetup.exe') $final -Force
        Write-Host ("Installer: {0} ({1:N0} MB)" -f $final, ((Get-Item $final).Length / 1MB))
    }

    # Small: .NET comes from Microsoft at install time when the PC doesn't have it.
    New-Installer 'Slim' $false (Join-Path $buildDir 'publish-slim') ''
    # Offline: self-contained, nothing to download.
    New-Installer 'Dist' $true (Join-Path $distDir 'PdfTranslator') '-offline'
}

# The portable SDK carries the runtimes, so the built app runs here without .NET installed.
if ($Run) { $env:DOTNET_ROOT = Split-Path $dotnet; & $exe }
