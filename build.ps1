<#
.SYNOPSIS
    Builds PDF Translator with the portable .NET 8 SDK, and optionally its installer.

.EXAMPLE
    .\build.ps1                 build (Release)
    .\build.ps1 -Run            build and start the app
    .\build.ps1 -Installer      also publish self-contained and make PdfTranslatorSetup-<version>.exe

.NOTES
    Deliverables go to dist\ in the project folder: dist\PdfTranslator (the self-contained app) and
    dist\PdfTranslatorSetup-<version>.exe. Compiler output and installer staging stay under
    %USERPROFILE%\source\build\PdfTranslator, off Google Drive (sync locks files mid-build).
    The installer is the BasicConnect-style single executable in tools\Setup: per-user by default,
    /allusers, /S, /D=, /nodesktop, /uninstall.
#>
param([string]$Configuration = "Release", [switch]$Run, [switch]$Installer)
$ErrorActionPreference = 'Stop'

$dotnet = Join-Path $env:USERPROFILE "source\tools\dotnet8\dotnet.exe"
if (-not (Test-Path $dotnet)) { throw "Portable SDK not found at $dotnet" }
$env:DOTNET_CLI_TELEMETRY_OPTOUT = "1"
$env:DOTNET_NOLOGO = "1"

$root = $PSScriptRoot
$buildDir = Join-Path $env:USERPROFILE "source\build\PdfTranslator"
$distDir = Join-Path $root "dist"
$project = Join-Path $root "PdfTranslator.csproj"

& $dotnet build $project -c $Configuration
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

$exe = Join-Path $buildDir "bin\$Configuration\net8.0-windows10.0.19041.0\win-x64\PdfTranslator.exe"
Write-Host "Built: $exe"

if ($Installer) {
    # Third-party notices from the packages this build restored; published with the app.
    & (Join-Path $root 'tools\Notices.ps1')

    # Version: from the csproj, plus the commit count when the sources are in git.
    $version = ([xml](Get-Content $project)).Project.PropertyGroup.Version | Where-Object { $_ } | Select-Object -First 1
    # Same stamp as GitVersion.targets gives the application: version.commits+hash[.dirty].
    $commits = 0; $hash = 'local'
    try {
        $commits = [int](git -C $root rev-list --count HEAD 2>$null)
        $hash = (git -C $root rev-parse --short HEAD 2>$null)
        if (git -C $root status --porcelain --untracked-files=no 2>$null) { $hash += '.dirty' }
    } catch { }
    $fileVersion = "$version.$commits"

    # 1. The application, self-contained so nothing has to be installed first.
    $publish = Join-Path $distDir 'PdfTranslator'
    if (Test-Path $publish) { Remove-Item $publish -Recurse -Force }
    New-Item -ItemType Directory -Path $distDir -Force | Out-Null
    & $dotnet publish $project -c Dist -r win-x64 --self-contained true -o $publish
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

    # 2. Payload: the published folder as one archive, plus the icon (and an EULA.txt when there is one).
    $payload = Join-Path $buildDir 'setup\payload'
    if (Test-Path $payload) { Remove-Item $payload -Recurse -Force }
    New-Item -ItemType Directory -Path $payload -Force | Out-Null
    Write-Host 'Payload : compressing...'
    Add-Type -AssemblyName System.IO.Compression.FileSystem
    [System.IO.Compression.ZipFile]::CreateFromDirectory($publish, (Join-Path $payload 'Payload.zip'),
        [System.IO.Compression.CompressionLevel]::Optimal, $false)
    Copy-Item (Join-Path $root 'Assets\PdfTranslator.ico') -Destination $payload -Force
    $eula = Join-Path $root 'EULA.txt'
    if (Test-Path $eula) { Copy-Item $eula -Destination $payload -Force; Write-Host 'Payload : EULA.txt included' }

    # 3. The installer's file version, generated (not tracked).
    $versionFile = Join-Path $root 'tools\Setup\Properties\BuildVersion.cs'
    @(
        '// GENERATED by build.ps1. Not tracked, not edited by hand.',
        "[assembly: System.Reflection.AssemblyFileVersion(`"$fileVersion`")]",
        "[assembly: System.Reflection.AssemblyInformationalVersion(`"$fileVersion+$hash`")]"
    ) | Set-Content -Path $versionFile -Encoding UTF8

    # 4. The installer itself, with the payload embedded.
    & $dotnet build (Join-Path $root 'tools\Setup\Setup.csproj') -c Release "-p:PayloadDir=$payload\"
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }
    $setupExe = Join-Path $buildDir 'setup\bin\Release\net472\PdfTranslatorSetup.exe'
    # An old installer that is open or still syncing (Google Drive) stays; it is not worth failing the build over.
    Get-ChildItem $distDir -Filter 'PdfTranslatorSetup-*.exe' -ErrorAction SilentlyContinue | Remove-Item -Force -ErrorAction SilentlyContinue
    $final = Join-Path $distDir "PdfTranslatorSetup-$fileVersion.exe"
    Copy-Item $setupExe $final -Force
    Write-Host ("Installer: {0} ({1:N0} MB)" -f $final, ((Get-Item $final).Length / 1MB))
}

if ($Run) { & $exe }
